"""Distil a constrained capture-point planner; not full-body reinforcement learning.

The labels come from a one-dimensional inverted-pendulum recovery calculation.
Training and held-out states have separate deterministic seeds. This policy only
suggests a support step and a hip counter-rotation; contacts remain authoritative.
"""
from pathlib import Path
import json
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
def dataset(seed,n):
 r=np.random.default_rng(seed)
 x=r.uniform([-0.25,-2.8,.68,.10,0],[.25,2.8,1.2,.42,1],(n,5))
 position,velocity,height,stance,brace=x.T
 omega=np.sqrt(9.81/height);capture=position+velocity/omega
 support=.095+stance*.5
 # A constrained support position, then the residual hip strategy. The
 # planner respects the finite step reach, rather than prescribing a pose.
 step=np.sign(capture)*np.minimum(.42,np.maximum(0,np.abs(capture)-support))
 hip=np.clip((position+velocity*.11-step*.30)/height,-.32,.32)
 y=np.stack([step,hip],axis=1)
 return x/np.array([.25,2.8,1.2,.42,1]),y/np.array([.42,.32])
x,y=dataset(20261025,16000);xv,yv=dataset(20261026,3000);xt,yt=dataset(20261027,5000)
r=np.random.default_rng(319);w=r.normal(0,.4,(5,24));b=np.zeros(24);v=r.normal(0,.15,(24,2));c=np.zeros(2)
params=[w,b,v,c];m=[np.zeros_like(p)for p in params];s=[p.copy()for p in m]
best=None;bestval=1e9
for epoch in range(1000):
 h=np.tanh(x@w+b);out=h@v+c;e=(out-y)/len(x)
 dh=(e@v.T)*(1-h*h)
 grads=[x.T@dh,dh.sum(0),h.T@e,e.sum(0)]
 for i,(p,g)in enumerate(zip(params,grads)):
  m[i]=.9*m[i]+.1*g;s[i]=.999*s[i]+.001*g*g
  p-=.012*(m[i]/(1-.9**(epoch+1)))/(np.sqrt(s[i]/(1-.999**(epoch+1)))+1e-8)
 if epoch%10==0:
  err=np.mean((np.tanh(xv@w+b)@v+c-yv)**2)
  if err<bestval:bestval=err;best=[p.copy()for p in params]
w,b,v,c=best;prediction=np.tanh(xt@w+b)@v+c
rmse=np.sqrt(np.mean(((prediction-yt)*[.42,.32])**2,axis=0))
accepted=bool(rmse[0]<.025 and rmse[1]<.025)
report=dict(result='passed'if accepted else'rejected',seed=20261025,algorithm='supervised distillation of constrained capture-point planner',
 inputs=['CoM displacement','disturbance velocity','pelvis height','stance width','brace'],outputs=['support step metres','hip rotation radians'],
 architecture=[5,24,2],train_states=16000,validation_states=3000,test_states=5000,held_out_rmse=dict(step_metres=float(rmse[0]),hip_radians=float(rmse[1])),
 scope='Reduced balance planner only; no trained whole-body RL, no learned football skill or Euphoria implementation.')
(ROOT/'config/learned-balance-policy.json').write_text(json.dumps(report,indent=2)+'\n')
if not accepted:raise SystemExit(json.dumps(report))
def array(name,value):return 'constexpr float '+name+'['+str(value.size)+']={'+','.join(f'{z:.9f}f'for z in value.flat)+'};\n'
header='''#pragma once
// Generated by train_balance_policy.py; constrained balance planner only.
#include <algorithm>
#include <cmath>
namespace football_balance_ml {
'''+array('w',w)+array('b',b)+array('v',v)+array('c',c)+'''
inline void predict(float position,float velocity,float height,float stance,bool brace,float &step,float &hip){
 const float x[5]={std::max(-1.f,std::min(1.f,position/.25f)),std::max(-1.f,std::min(1.f,velocity/2.8f)),height/1.2f,stance/.42f,brace?1.f:0.f};
 float result[2]={c[0],c[1]};for(unsigned j=0;j<24;++j){float a=b[j];for(unsigned i=0;i<5;++i)a+=x[i]*w[i*24+j];
  const float h=std::tanh(a);for(unsigned k=0;k<2;++k)result[k]+=h*v[j*2+k];}
 step=std::max(-.42f,std::min(.42f,result[0]*.42f));hip=std::max(-.32f,std::min(.32f,result[1]*.32f));
}
}
'''
(ROOT/'src/onthepitch/player/humanoid/learned_balance_policy.hpp').write_text(header)
print(json.dumps(report))
